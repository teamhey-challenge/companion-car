// docs/transitions.json is generated by hey-relay (`bun run export:transitions`) from its TRANSITIONS table, the one
// source of truth for which message a trip state accepts. The test checks every phase's enabled commands against it.
// A relay checkout (HEY_RELAY_DIR, default ../hey-relay) wins, so a local run sees the relay's current table; without
// one the copy committed in this repository's docs/ is used.
val copyRelayTransitions = tasks.register<Copy>("copyRelayTransitions") {
    val relayDir = System.getenv("HEY_RELAY_DIR")?.takeIf { it.isNotBlank() }?.let { file(it).takeIf { f -> f.isAbsolute } ?: rootDir.resolve(it) }
        ?: rootDir.resolve("../hey-relay")
    val fromRelay = relayDir.resolve("docs/transitions.json")
    from(if (fromRelay.isFile) fromRelay else rootDir.resolve("docs/transitions.json"))
    into(layout.buildDirectory.dir("relay-transitions/relay-transitions"))
}
tasks.matching { it.name.endsWith("UnitTestJavaRes") }.configureEach { dependsOn(copyRelayTransitions) }

