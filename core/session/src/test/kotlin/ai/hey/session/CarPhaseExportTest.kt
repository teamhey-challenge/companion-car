/**
 * Exports what `phaseOf` and `CarPhase.enabled` decide to docs/car-phases.json, which hey-relay's contract test
 * (test/contract/car-phase.ts) reads instead of a hand-written copy. The file is a generated artifact: this test fails
 * when the committed file differs from a fresh export, and rewrites it when HEY_EXPORT_CAR_PHASES=1:
 *
 *   HEY_EXPORT_CAR_PHASES=1 ./gradlew :core:session:testDebugUnitTest --tests '*CarPhaseExportTest*'
 *
 * Rows are keyed by everything `phaseOf` looks at: trip state, whether a join waits, whether a card exists, whether
 * the D4 panel is open, whether open questions/pins wait (`actionableCount > requestsDismissedAt`) and the driving status.
 */
class CarPhaseExportTest {
    private val place = Place("p1", "Hotel", "호텔", "서울 중구", "서울", 37.5, 127.0)
    private val question = RequestItem("req_1", RequestKind.Preset, null, "창문을 열어도 될까요?", true, RequestState.Received, ts = 0)
    private val pin = PassengerPin(2, LatLng(37.5, 127.0), DropoffKind.Pin, null, null, null, "핀", "pin", status = PinProposalStatus.Pending)

    private fun drivingName(d: DrivingStatus) = when (d) {
        DrivingStatus.Parked -> "PARKED"
        DrivingStatus.Driving -> "DRIVING"
        DrivingStatus.Unknown -> "UNKNOWN"
    }

    private fun phaseName(p: CarPhase): String = when (p) {
        CarPhase.Driving -> "Driving"
        CarPhase.Waiting -> "Waiting"
        is CarPhase.JoinRequest -> "JoinRequest"
        is CarPhase.AwaitingCard -> "AwaitingCard"
        is CarPhase.CardSent -> "CardSent"
        is CarPhase.InTrip -> "InTrip"
        is CarPhase.DropoffProposal -> "DropoffProposal"
        is CarPhase.Requests -> "Requests"
        is CarPhase.Arrived -> "Arrived"
    }

    private fun export(): JsonObject = buildJsonObject {
        put("comment", "Generated by CarPhaseExportTest from phaseOf/CarPhase.enabled/CarCommand.wire. Do not edit; regenerate.")
        put("commands", buildJsonObject {
            for (c in CarCommand.entries) put(c.name, buildJsonArray { c.wire.sorted().forEach { add(JsonPrimitive(it)) } })
        })
        val descriptor = CarView.serializer().descriptor
        put("viewFields", buildJsonArray { for (i in 0 until descriptor.elementsCount) add(JsonPrimitive(descriptor.getElementName(i))) })
        put("viewRequired", buildJsonArray {
            for (i in 0 until descriptor.elementsCount) if (!descriptor.isElementOptional(i)) add(JsonPrimitive(descriptor.getElementName(i)))
        })
        put("rows", buildJsonArray {
            for (state in TripState.entries) for (driving in listOf(DrivingStatus.Parked, DrivingStatus.Driving, DrivingStatus.Unknown)) {
                for (join in listOf(false, true)) for (card in listOf(false, true)) for (dropoff in listOf(false, true)) for (waits in listOf(false, true)) {
                    val view = CarView(
                        state = state, carCode = "C", plateSuffix = "1", driving = DrivingState.PARKED,
                        pendingJoin = if (join) PendingJoin("jr", Lang.En, 1, 0, "47") else null,
                        card = if (card) CarCardView(place, emptyList(), emptyList()) else null,
                        requests = if (waits) listOf(question) else emptyList(),
                        pendingPins = if (waits) listOf(pin) else emptyList(),
                    )
                    val local = LocalUi(panel = if (dropoff) Panel.Dropoff else Panel.None, requestsDismissedAt = 0)
                    val phase = phaseOf(view, driving, local)
                    add(buildJsonObject {
                        put("state", state.name)
                        put("driving", drivingName(driving))
                        put("join", join)
                        put("card", card)
                        put("dropoff", dropoff)
                        put("waits", waits)
                        put("phase", phaseName(phase))
                        put("enabled", buildJsonArray {
                            if (phase is CarPhase.Parked) phase.enabled.map { it.name }.sorted().forEach { add(JsonPrimitive(it)) }
                        })
                    })
                }
            }
        })
    }

    private fun target(): File {
        // gradle runs unit tests with the module directory (core/session) as the working directory
        var dir: File? = File(System.getProperty("user.dir")).absoluteFile
        while (dir != null && !File(dir, "docs").isDirectory) dir = dir.parentFile
        return File(requireNotNull(dir) { "repository root with docs/ not found above ${System.getProperty("user.dir")}" }, "docs/car-phases.json")
    }

    @Test fun docsCarPhasesJsonIsCurrent() {
        val fresh = Json { prettyPrint = false }.encodeToString(JsonObject.serializer(), export()).let { it.replace("},{", "},\n{") } + "\n"
        val file = target()
        if (System.getenv("HEY_EXPORT_CAR_PHASES") == "1") {
            file.writeText(fresh)
            return
        }
        assertTrue("${file.path} is missing; run with HEY_EXPORT_CAR_PHASES=1", file.isFile)
        assertEquals(
            "docs/car-phases.json is stale: phaseOf/CarPhase/CarCommand/CarView changed. Regenerate with HEY_EXPORT_CAR_PHASES=1 ./gradlew :core:session:testDebugUnitTest --tests '*CarPhaseExportTest*' and commit it.",
            file.readText(),
            fresh,
        )
    }

    @Test fun theExportCoversEveryPhase() {
        val rows = export().getValue("rows") as JsonArray
        val names = rows.map { ((it as JsonObject).getValue("phase") as JsonPrimitive).content }.toSet()
        assertEquals(
            setOf("Driving", "Waiting", "JoinRequest", "AwaitingCard", "CardSent", "InTrip", "DropoffProposal", "Requests", "Arrived"),
            names,
        )
    }
}
