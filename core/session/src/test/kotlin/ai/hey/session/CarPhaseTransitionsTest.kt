/**
 * T3. The relay's `TRANSITIONS` table (docs/transitions.json, generated by hey-relay) says which message a trip state
 * accepts from the car. Every phase the car can be in must enable only commands whose messages the table lists for
 * that state, so the car never offers a button the relay answers with BAD_REQUEST (review finding B3).
 */
class CarPhaseTransitionsTest {
    private val table: Map<String, Set<String>> = run {
        val text = javaClass.getResourceAsStream("/relay-transitions/transitions.json")!!.bufferedReader().use { it.readText() }
        Json.parseToJsonElement(text).jsonObject.mapValues { (_, rows) ->
            rows.jsonArray.map { it.jsonObject }.filter { it.getValue("role").jsonPrimitive.content in setOf("car", "car-or-lead") }
                .map { it.getValue("type").jsonPrimitive.content }.toSet()
        }
    }

    private val place = Place("p1", "Hotel", "호텔", "서울 중구", "서울", 37.5, 127.0)
    private val question = RequestItem("req_1", RequestKind.Preset, null, "창문을 열어도 될까요?", true, RequestState.Received, ts = 0)

    /** Every combination of snapshot content and local UI flags the car can be in while parked. */
    private fun phasesIn(state: TripState): List<CarPhase.Parked> {
        val out = ArrayList<CarPhase.Parked>()
        for (card in listOf(false, true)) for (join in listOf(false, true)) for (asks in listOf(false, true)) {
            for (panel in Panel.entries) for (dismissed in listOf(0, 1)) {
                val view = CarView(
                    state = state, carCode = "C", plateSuffix = "1", driving = DrivingState.PARKED,
                    pendingJoin = if (join) PendingJoin("jr", Lang.En, 1, 0, "47") else null,
                    card = if (card) CarCardView(place, emptyList(), emptyList()) else null,
                    requests = if (asks) listOf(question) else emptyList(),
                )
                out += phaseOf(view, DrivingStatus.Parked, LocalUi(panel, dismissed)) as CarPhase.Parked
            }
        }
        return out
    }

    /** IDLE is the car's name for "no trip"; the relay's table has no row for it, and no command may be enabled there. */
    private fun accepted(state: TripState): Set<String> = if (state == TripState.IDLE) emptySet() else table.getValue(state.name)

    @Test fun theTableCoversEveryTripStateThatIsATripPhase() {
        for (state in TripState.entries - TripState.IDLE) {
            assertTrue("$state missing from docs/transitions.json", table.containsKey(state.name))
        }
    }

    @Test fun everyPhaseEnablesOnlyCommandsTheRelayAcceptsInThatState() {
        for (state in TripState.entries) {
            val accepted = accepted(state)
            for (phase in phasesIn(state)) {
                for (command in phase.enabled) {
                    val missing = command.wire - accepted
                    assertTrue("$phase enables $command in $state but the relay rejects $missing there", missing.isEmpty())
                }
            }
        }
    }

    /** The table is not vacuous: it does refuse these, so a phase listing them (the pre-fix BoardingCard did) fails above. */
    @Test fun theTableRefusesWhatTheOldBoardingCardOffered() {
        assertTrue(CarCommand.StartRoute.wire.none { it in table.getValue("CONNECTED") })
        assertTrue(CarCommand.Propose.wire.none { it in table.getValue("CONNECTED") })
        assertTrue(CarCommand.Recheck.wire.none { it in table.getValue("IN_TRIP") })
        assertEquals(true, CarCommand.End.wire.all { it in table.getValue("ARRIVED") })
    }
}
